#!/usr/bin/env python3
"""Builds the Dust Bin games' own pages (rap/index.html, guitar/index.html) from fight/index.html.

Rap Battle and Guitar Battle run inside the fighting game's page (they share its screens, sound and art),
so each of their pages is a copy of fight/index.html with its own title and link preview, plus
window.POF_SOLO, which makes js/app.js skip the fight's title and open that game straight away.

Run it again after changing fight/index.html:   python3 tools/solo-pages.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = [
    ('rap', 'Rap Battle', 'Toly vs Vitalik, three rounds, hosted by MC Satoshi. From the Proof of Fight Dust Bin.'),
    ('guitar', 'Guitar Battle', 'Shred against a founder over a real rock song. From the Proof of Fight Dust Bin.'),
]

src = open(os.path.join(ROOT, 'fight', 'index.html'), encoding='utf-8').read()

def sub(pattern, repl, text):
    out, n = re.subn(pattern, repl, text, count=1)
    if n != 1:
        raise SystemExit('fight/index.html no longer has: ' + pattern)
    return out

for mode, name, desc in PAGES:
    t = src
    t = sub(r'<title>[^<]*</title>', '<title>%s · Proof of Fight</title>' % name, t)
    t = sub(r'(<meta name="description" content=")[^"]*', r'\g<1>' + desc, t)
    t = sub(r'(<meta property="og:title" content=")[^"]*', r'\g<1>' + name, t)
    t = sub(r'(<meta property="og:description" content=")[^"]*', r'\g<1>' + desc, t)
    t = sub(r'(<meta property="og:url" content=")[^"]*', r'\g<1>https://proofoffight.com/%s/' % mode, t)
    t = sub(r'  <script src="js/data.js"></script>',
            '  <!-- Generated by tools/solo-pages.py from fight/index.html: edit that, then run the tool. -->\n'
            '  <script>window.POF_SOLO = \'%s\';</script>\n  <script src="js/data.js"></script>' % mode, t)
    os.makedirs(os.path.join(ROOT, mode), exist_ok=True)
    open(os.path.join(ROOT, mode, 'index.html'), 'w', encoding='utf-8').write(t)
    print('wrote', mode + '/index.html')
